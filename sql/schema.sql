-- =====================================================================
-- BudgetKeeper — схема базы данных PostgreSQL 15+
-- Учебный проект: учёт личных расходов с ИИ-категоризацией операций
--
-- Скрипт создаёт предметные таблицы. Служебные таблицы Django
-- (auth_*, django_*, users_groups, users_user_permissions) создаются
-- миграциями фреймворка и здесь не дублируются.
--
-- Выполнение:
--   CREATE DATABASE budgetkeeper WITH ENCODING 'UTF8' TEMPLATE template0;
--   \c budgetkeeper
--   \i sql/schema.sql
-- =====================================================================

BEGIN;

-- 1. Пользователи -----------------------------------------------------
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(128) NOT NULL,
    full_name     VARCHAR(150) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'user'
                  CONSTRAINT ck_users_role CHECK (role IN ('user', 'admin')),
    is_active     BOOLEAN      NOT NULL DEFAULT TRUE,
    is_staff      BOOLEAN      NOT NULL DEFAULT FALSE,
    is_superuser  BOOLEAN      NOT NULL DEFAULT FALSE,
    last_login    TIMESTAMPTZ,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE users IS 'Учётные записи BudgetKeeper; вход по email';
COMMENT ON COLUMN users.password_hash IS 'Хеш пароля (PBKDF2), открытый пароль не хранится';

-- 2. Одноразовые токены восстановления пароля ------------------------
CREATE TABLE password_reset_token (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL
               REFERENCES users (id) ON DELETE CASCADE,
    token_hash CHAR(64)    NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at    TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE password_reset_token IS
    'Одноразовые токены сброса пароля; хранится только SHA-256 хеш';

CREATE INDEX idx_prt_user_id ON password_reset_token (user_id);
CREATE INDEX idx_prt_expires ON password_reset_token (expires_at);

-- 3. Счета пользователя ----------------------------------------------
CREATE TABLE accounts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL
                    REFERENCES users (id) ON DELETE CASCADE,
    name            VARCHAR(100) NOT NULL,
    account_type    VARCHAR(20)  NOT NULL DEFAULT 'card'
                    CONSTRAINT ck_accounts_type
                    CHECK (account_type IN ('cash', 'card', 'bank')),
    initial_balance NUMERIC(12,2) NOT NULL DEFAULT 0,
    currency        VARCHAR(3)   NOT NULL DEFAULT 'RUB',
    is_active       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_accounts_user_name UNIQUE (user_id, name)
);

COMMENT ON TABLE accounts IS 'Карты, наличные и банковские счета пользователя';

-- 4. Категории доходов и расходов ------------------------------------
CREATE TABLE categories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL
               REFERENCES users (id) ON DELETE CASCADE,
    name       VARCHAR(80) NOT NULL,
    kind       VARCHAR(10) NOT NULL DEFAULT 'expense'
               CONSTRAINT ck_categories_kind
               CHECK (kind IN ('income', 'expense')),
    color      VARCHAR(7)  NOT NULL DEFAULT '#4f46e5',
    is_system  BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_categories_user_name_kind UNIQUE (user_id, name, kind)
);

COMMENT ON TABLE categories IS 'Справочник статей доходов и расходов';

-- 5. Операции — главная сущность предметной области ------------------
CREATE TABLE operations (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL
                   REFERENCES users (id) ON DELETE CASCADE,
    account_id     BIGINT       NOT NULL
                   REFERENCES accounts (id) ON DELETE RESTRICT,
    category_id    BIGINT       NOT NULL
                   REFERENCES categories (id) ON DELETE RESTRICT,
    operation_type VARCHAR(10)  NOT NULL DEFAULT 'expense'
                   CONSTRAINT ck_operations_type
                   CHECK (operation_type IN ('income', 'expense')),
    amount         NUMERIC(12,2) NOT NULL
                   CONSTRAINT ck_operations_amount_positive CHECK (amount > 0),
    description    TEXT         NOT NULL DEFAULT '',
    occurred_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by_ai  BOOLEAN      NOT NULL DEFAULT FALSE,
    ai_confidence  NUMERIC(4,3)
                   CONSTRAINT ck_operations_ai_confidence
                   CHECK (ai_confidence IS NULL OR ai_confidence BETWEEN 0 AND 1),
    is_deleted     BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE operations IS 'Доходы и расходы пользователя';
COMMENT ON COLUMN operations.is_deleted IS 'Мягкое удаление: запись остаётся в БД';

CREATE INDEX idx_operations_user_date ON operations (user_id, occurred_at);
CREATE INDEX idx_operations_category ON operations (category_id);
CREATE INDEX idx_operations_account ON operations (account_id);

-- 6. Бюджеты (лимиты) по категориям на месяц -------------------------
CREATE TABLE budgets (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL
                 REFERENCES users (id) ON DELETE CASCADE,
    category_id  BIGINT       NOT NULL
                 REFERENCES categories (id) ON DELETE CASCADE,
    period_start DATE         NOT NULL,
    limit_amount NUMERIC(12,2) NOT NULL
                 CONSTRAINT ck_budgets_limit_positive CHECK (limit_amount > 0),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_budgets_user_category_period
        UNIQUE (user_id, category_id, period_start),
    CONSTRAINT ck_budgets_period_first_day
        CHECK (EXTRACT(DAY FROM period_start) = 1)
);

COMMENT ON TABLE budgets IS 'Месячные лимиты расходов по категориям';

-- 7. История ИИ-подсказок --------------------------------------------
CREATE TABLE ai_suggestions (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT      NOT NULL
                          REFERENCES users (id) ON DELETE CASCADE,
    operation_id          BIGINT
                          REFERENCES operations (id) ON DELETE SET NULL,
    input_text            TEXT        NOT NULL,
    suggested_category_id BIGINT
                          REFERENCES categories (id) ON DELETE SET NULL,
    confidence            NUMERIC(4,3) NOT NULL DEFAULT 0
                          CONSTRAINT ck_ai_suggestions_confidence
                          CHECK (confidence BETWEEN 0 AND 1),
    source                VARCHAR(10) NOT NULL DEFAULT 'rules'
                          CONSTRAINT ck_ai_suggestions_source
                          CHECK (source IN ('rules', 'llm')),
    accepted              BOOLEAN,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE ai_suggestions IS
    'Журнал подсказок ИИ: входной текст, категория, уверенность, источник';

CREATE INDEX idx_ai_suggestions_user ON ai_suggestions (user_id);

COMMIT;
